#!/usr/bin/env node

import { pathToFileURL } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export const CWE_SOURCE_URL =
  'https://cwe-api.mitre.org/api/v1/cwe/weakness/all';
export const EXPECTED_CWE_VERSION = '4.20';
export const EXPECTED_CWE_RELEASE_DATE = '2026-04-30';
export const EXPECTED_CWE_ENTRY_COUNT = 969;

const normalizeId = value => `CWE-${Number(value)}`;

const compareVersions = (left, right) => {
  const leftParts = left.split('.').map(Number);
  const rightParts = right.split('.').map(Number);
  const length = Math.max(leftParts.length, rightParts.length);

  for (let index = 0; index < length; index += 1) {
    const difference = (leftParts[index] ?? 0) - (rightParts[index] ?? 0);
    if (difference !== 0) return difference;
  }

  return 0;
};

export const deriveReleaseMetadata = weaknesses => {
  const releases = weaknesses.flatMap(weakness =>
    (weakness.ContentHistory ?? []).flatMap(entry => {
      const version = entry.ModificationVersion ?? entry.SubmissionVersion;
      const releaseDate =
        entry.ModificationReleaseDate ?? entry.SubmissionReleaseDate;
      return version && releaseDate ? [{ version, releaseDate }] : [];
    }),
  );

  return releases.sort((left, right) =>
    compareVersions(right.version, left.version),
  )[0];
};

const replacementIdsFor = weakness => {
  if (weakness.Status !== 'Deprecated') return [];

  const matches = weakness.Description?.matchAll(/\bCWE-(\d+)\b/g) ?? [];
  return [
    ...new Set(
      [...matches]
        .map(match => normalizeId(match[1]))
        .filter(id => id !== normalizeId(weakness.ID)),
    ),
  ];
};

export const normalizeWeaknesses = payload => {
  if (!payload || !Array.isArray(payload.Weaknesses)) {
    throw new Error('MITRE CWE response does not contain a Weaknesses array.');
  }

  const { Weaknesses: weaknesses } = payload;
  const metadata = deriveReleaseMetadata(weaknesses);

  if (
    weaknesses.length !== EXPECTED_CWE_ENTRY_COUNT ||
    metadata?.version !== EXPECTED_CWE_VERSION ||
    metadata.releaseDate !== EXPECTED_CWE_RELEASE_DATE
  ) {
    throw new Error(
      `Unexpected CWE release: version=${metadata?.version ?? 'unknown'}, ` +
        `releaseDate=${metadata?.releaseDate ?? 'unknown'}, ` +
        `entries=${weaknesses.length}. Review the upstream release before updating.`,
    );
  }

  const entries = weaknesses
    .map(weakness => ({
      id: normalizeId(weakness.ID),
      name: String(weakness.Name).trim(),
      status: weakness.Status,
      deprecated: weakness.Status === 'Deprecated',
      replacementIds: replacementIdsFor(weakness),
    }))
    .sort(
      (left, right) => Number(left.id.slice(4)) - Number(right.id.slice(4)),
    );

  const ids = new Set(entries.map(entry => entry.id));
  if (ids.size !== entries.length) {
    throw new Error('MITRE CWE response contains duplicate IDs.');
  }

  return { entries, metadata };
};

export const renderCatalogModule = entries => {
  const metadata = [
    'export const CWE_CATALOG_4_20_METADATA = {',
    `  version: '${EXPECTED_CWE_VERSION}',`,
    `  releaseDate: '${EXPECTED_CWE_RELEASE_DATE}',`,
    `  sourceUrl: '${CWE_SOURCE_URL}',`,
    `  entryCount: ${EXPECTED_CWE_ENTRY_COUNT},`,
    '} as const;',
  ].join('\n');

  return [
    '// Generated by scripts/sync-cwe-catalog.mjs. Do not edit manually.',
    metadata,
    '',
    `export const CWE_CATALOG_4_20 = ${JSON.stringify(entries)} as const;`,
    '',
  ].join('\n');
};

const loadPayload = async inputPath => {
  if (inputPath) {
    return JSON.parse(await readFile(path.resolve(inputPath), 'utf8'));
  }

  const response = await fetch(CWE_SOURCE_URL, {
    headers: { accept: 'application/json' },
  });
  if (!response.ok) {
    throw new Error(`MITRE CWE request failed with HTTP ${response.status}.`);
  }
  return response.json();
};

export const syncCweCatalog = async ({ inputPath, outputPath } = {}) => {
  const payload = await loadPayload(inputPath);
  const { entries } = normalizeWeaknesses(payload);
  const target = path.resolve(outputPath ?? 'generated/cwe/cweCatalog.4.20.ts');
  await writeFile(target, renderCatalogModule(entries), 'utf8');
  return { outputPath: target, entryCount: entries.length };
};

const isDirectExecution =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirectExecution) {
  const inputIndex = process.argv.indexOf('--input');
  const outputIndex = process.argv.indexOf('--output');
  const result = await syncCweCatalog({
    inputPath: inputIndex >= 0 ? process.argv[inputIndex + 1] : undefined,
    outputPath: outputIndex >= 0 ? process.argv[outputIndex + 1] : undefined,
  });
  console.log(
    `Wrote ${result.entryCount} CWE entries to ${result.outputPath}.`,
  );
}
